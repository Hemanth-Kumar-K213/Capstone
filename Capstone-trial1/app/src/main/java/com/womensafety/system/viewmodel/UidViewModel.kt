package com.womensafety.system.viewmodel

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.womensafety.system.data.model.WeeklyUid
import com.womensafety.system.data.repository.AuthRepository
import com.womensafety.system.data.repository.UidRepository
import com.womensafety.system.utils.DateUtils
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.launch

/**
 * READ-ONLY ViewModel for displaying and sharing the weekly UID.
 *
 * IMPORTANT: This ViewModel does NOT generate or rotate UIDs.
 * It only observes the backend-generated UID from Firestore via [UidRepository].
 * UID generation and rotation are handled exclusively by Firebase Cloud Functions.
 */
class UidViewModel(
    private val authRepository: AuthRepository = AuthRepository(),
    private val uidRepository: UidRepository = UidRepository()
) : ViewModel() {

    data class UidState(
        val currentUid: WeeklyUid? = null,
        val isLoading: Boolean = true,
        val error: String? = null,
        val expiryText: String = "",
        val isActive: Boolean = false
    )

    private val _uidState = MutableStateFlow(UidState())
    val uidState: StateFlow<UidState> = _uidState.asStateFlow()

    /**
     * Loads the current active UID from Firestore (read-only).
     * The UID was generated by Cloud Functions on the backend.
     */
    fun loadCurrentUid() {
        val userId = authRepository.currentUserId ?: return

        viewModelScope.launch {
            _uidState.value = _uidState.value.copy(isLoading = true)

            val result = uidRepository.getCurrentUid(userId)
            if (result.isSuccess) {
                val uid = result.getOrNull()
                _uidState.value = UidState(
                    currentUid = uid,
                    isLoading = false,
                    expiryText = uid?.let { DateUtils.getTimeUntilExpiry(it.expiresAt) } ?: "",
                    isActive = uid?.isCurrentlyActive ?: false
                )
            } else {
                _uidState.value = UidState(
                    isLoading = false,
                    error = "Unable to load your Safety UID. It may not have been generated yet."
                )
            }
        }
    }

    /**
     * Returns the share text for the current UID.
     */
    fun getShareText(): String? {
        val uid = _uidState.value.currentUid?.uid ?: return null
        return "My current Trinetra UID is: $uid"
    }
}
