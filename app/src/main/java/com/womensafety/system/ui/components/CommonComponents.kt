/**
 * Reusable Modern Surface Card adapting cleanly to Light and Dark modes.
 * Uses a Column container with default internal padding so that children are
 * laid out sequentially from top to bottom, completely preventing accidental overlap.
 */
@Composable
fun AppCard(
    modifier: Modifier = Modifier,
    cornerRadius: Dp = 18.dp,
    accentGradient: Brush? = null,
    onClick: (() -> Unit)? = null,
    contentPadding: PaddingValues = PaddingValues(16.dp),
    content: @Composable ColumnScope.() -> Unit
) {
    val isDark = LocalDarkTheme.current
    val surfaceColor = if (isDark) SurfaceDark else SurfaceLight
    val borderColor = if (isDark) OutlineDark.copy(alpha = 0.8f) else OutlineLight
    val shape = RoundedCornerShape(cornerRadius)

    val cardModifier = modifier
        .fillMaxWidth()
        .clip(shape)
        .border(
            width = 1.dp,
            brush = Brush.linearGradient(
                colors = listOf(borderColor, borderColor.copy(alpha = 0.4f))
            ),
            shape = shape
        )

    Card(
        onClick = { onClick?.invoke() },
        enabled = onClick != null,
        modifier = cardModifier,
        shape = shape,
        colors = CardDefaults.cardColors(
            containerColor = surfaceColor
        ),
        elevation = CardDefaults.cardElevation(
            defaultElevation = if (isDark) 0.dp else 2.dp,
            pressedElevation = if (isDark) 2.dp else 4.dp
        )
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .then(
                    if (accentGradient != null) Modifier.background(accentGradient)
                    else Modifier
                )
                .padding(contentPadding),
            content = content
        )
    }
}

/**
 * Modern screen header with navigation back button, title, and optional subtitle.
 */
@Composable
fun ScreenHeader(
    title: String,
    subtitle: String? = null,
    onBack: (() -> Unit)? = null,
    modifier: Modifier = Modifier,
    actions: @Composable RowScope.() -> Unit = {}
) {
    Column(modifier = modifier.fillMaxWidth()) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            if (onBack != null) {
                IconButton(
                    onClick = onBack,
                    modifier = Modifier
                        .size(42.dp)
                        .clip(CircleShape)
                        .background(MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.8f))
                        .border(
                            width = 1.dp,
                            color = MaterialTheme.colorScheme.outline.copy(alpha = 0.5f),
                            shape = CircleShape
                        )
                ) {
                    Icon(
                        imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                        contentDescription = "Back",
                        tint = MaterialTheme.colorScheme.onSurface,
                        modifier = Modifier.size(20.dp)
                    )
                }
                Spacer(modifier = Modifier.width(14.dp))
            }
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = title,
                    style = MaterialTheme.typography.titleLarge,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onBackground,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
                if (subtitle != null) {
                    Spacer(modifier = Modifier.height(2.dp))
                    Text(
                        text = subtitle,
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis
                    )
                }
            }
            actions()
        }
    }
}

